"""
Evaluation Runner for Benchmark Bundles.
Evaluates precision, recall, and detection accuracy across genuine and tampered bundles.
Generates docs/RESULTS_TABLE.md.
"""

import os
import sys
from pathlib import Path

# Add root directory to sys.path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fastapi.testclient import TestClient
from backend.app.main import app

client = TestClient(app)
BUNDLES_DIR = Path("samples/bundles")
RESULTS_MD = Path("docs/RESULTS_TABLE.md")


def run_evaluation_suite():
    bundles = sorted([b for b in BUNDLES_DIR.iterdir() if b.is_dir()])
    print(f"Running evaluation on {len(bundles)} bundles...")

    results = []
    
    tp, fp, tn, fn = 0, 0, 0, 0

    for b in bundles:
        bundle_name = b.name
        is_genuine = bundle_name.startswith("genuine_")
        
        # Create investigation
        r_inv = client.post("/investigations")
        inv_id = r_inv.json()["investigation_id"]

        files = []
        for pdf_file in b.glob("*.pdf"):
            files.append(("files", (pdf_file.name, open(pdf_file, "rb"), "application/pdf")))

        client.post(f"/investigations/{inv_id}/documents", files=files)
        client.post(f"/investigations/{inv_id}/process")

        inv = client.get(f"/investigations/{inv_id}").json()
        findings = client.get(f"/investigations/{inv_id}/findings").json()

        finding_count = len(findings)
        priority = inv["review_priority"]
        score = inv["priority_score"]
        
        # Classification of prediction:
        # A bundle with findings > 0 or priority in (medium, high) is predicted as Anomaly/Tampered
        has_anomalies = finding_count > 0 or priority in ("medium", "high")

        if is_genuine:
            if not has_anomalies:
                tn += 1
                status = "PASS (True Negative)"
            else:
                fp += 1
                status = "FAIL (False Positive)"
        else:
            if has_anomalies:
                tp += 1
                status = "PASS (True Positive)"
            else:
                fn += 1
                status = "FAIL (False Negative)"

        rule_ids = list(set([f["rule_id"] for f in findings]))
        results.append({
            "bundle": bundle_name,
            "type": "Genuine" if is_genuine else "Tampered",
            "findings": finding_count,
            "priority": priority.upper(),
            "score": score,
            "rules_fired": ", ".join(rule_ids) if rule_ids else "None",
            "status": status,
        })

    # Metrics
    precision = (tp / (tp + fp)) if (tp + fp) > 0 else 1.0
    recall = (tp / (tp + fn)) if (tp + fn) > 0 else 1.0
    accuracy = (tp + tn) / len(bundles) if bundles else 1.0
    f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0

    print("\n" + "=" * 60)
    print("EVALUATION RESULTS SUMMARY")
    print("=" * 60)
    print(f"Total Bundles Evaluated: {len(bundles)}")
    print(f"Accuracy:  {accuracy:.1%}")
    print(f"Precision: {precision:.1%}")
    print(f"Recall:    {recall:.1%}")
    print(f"F1 Score:  {f1:.3f}")
    print("=" * 60)

    # Write Markdown Table
    RESULTS_MD.parent.mkdir(parents=True, exist_ok=True)
    with open(RESULTS_MD, "w", encoding="utf-8") as f:
        f.write("# PS-2 Forensic & Contextual Intelligence — Evaluation Results\n\n")
        f.write("> **System Principle:** 100% deterministic rule-based analysis. Zero LLM hallucinations.\n\n")
        f.write("## Performance Metrics\n\n")
        f.write(f"- **Accuracy:** {accuracy:.1%}\n")
        f.write(f"- **Precision:** {precision:.1%}\n")
        f.write(f"- **Recall:** {recall:.1%}\n")
        f.write(f"- **F1 Score:** {f1:.3f}\n")
        f.write(f"- **Total Test Bundles:** {len(bundles)}\n\n")
        f.write("## Detailed Bundle Results\n\n")
        f.write("| Bundle Name | Ground Truth | Findings | Priority | Score | Triggered Rules | Status |\n")
        f.write("|---|---|---|---|---|---|---|\n")
        for r in results:
            f.write(f"| `{r['bundle']}` | {r['type']} | {r['findings']} | {r['priority']} | {r['score']} | {r['rules_fired']} | {r['status']} |\n")
        f.write("\n\n---\n*Generated by `eval/run_eval.py` in offline test mode.*\n")

    print(f"\nWrote full metrics table to {RESULTS_MD}")


if __name__ == "__main__":
    run_evaluation_suite()
